-- ============================================================
-- DEATH / RESPAWN / REVIVE
-- ============================================================
-- The player loses the weapons in the inventory (equipped and stored) when:
--   * he dies and respawns normally            (RemoveArmoryWeaponsOnRespawn)
--   * the server restarts / the map changes    (RemoveWeaponsOnServerRestart)
--   * he switches to another character          (RemoveWeaponsOnCharacterChange)
-- He KEEPS them when a medic revives him. Krakens Medical only knocks the
-- player down (he never really dies), so a medic revive keeps everything.
-- Job default weapons (`weapons = {...}` of the DarkRP job), armor and all
-- other inventory items are always kept.
--
-- RemoveAllWeapons = true  -> every weapon item is removed
-- RemoveAllWeapons = false -> only armory weapons (job loadout + armory terminal)
--
-- ReviveMaxTime / ReviveMaxDistance: optional fallback for revive addons that
-- really kill and respawn the player at the body. A spawn within that time AND
-- distance of the death counts as a revive. 0 = off (otherwise a player who
-- dies next to the spawn point would keep the weapons). Revive addons can also
-- call GRNInventory.MarkRevived(ply) before/right after ply:Spawn().
C.Respawn = {
    RemoveAllWeapons = true,
    RemoveArmoryWeaponsOnRespawn = true,
    RemoveWeaponsOnServerRestart = true,
    RemoveWeaponsOnCharacterChange = true,
    ReviveMaxTime = 0,
    ReviveMaxDistance = 0,
    -- How long after the spawn the revive check runs (revive addons usually
    -- move the player to the body right after ply:Spawn()).
    CheckDelay = 0.5,
}

-- ============================================================
-- BACKPACK OPEN / CLOSE ANIMATION
-- ============================================================
-- The animation assets are bundled directly inside grn_inventory, so the
-- original backpack addon does NOT need to remain installed.
C.BackpackAnimation = {
    Enabled = true,
    WeaponClass = "weapon_grn_inventory_backpack",

    -- The backpack animation starts immediately when I is pressed.
    -- The DHTML inventory appears a moment later, while the backpack is still
    -- visible underneath the transparent interface.
    OpenUIDelay = 0,

    -- Safety fallback in case a custom viewmodel reports an invalid duration.
    CloseFallbackDuration = 1.10,

    -- Only animate when the player is alive. Spectators/dead players fall back
    -- to opening the normal UI without forcing a SWEP.
    AliveOnly = true,

    -- ========================================================
    -- OPTIONAL VISUAL BACKPACK REPLACEMENT
    -- ========================================================
    -- The original animated S.T.A.L.K.E.R. 2 viewmodel remains loaded and
    -- performs all of the open/idle/close animations, but its backpack mesh is
    -- hidden. A separate model is then drawn on the animated jnt_backpack bone.
    --
    -- Set Enabled = false to instantly return to the original animated model.
    Replacement = {
        Enabled = true,
        Model = "models/vortexgaming/tc13u/armor/backpack.mdl",

        -- Hide the original backpack while keeping its skeleton/animations as
        -- the invisible animation driver.
        HideOriginal = true,

        -- "bone" is recommended and works with normal/static prop models.
        -- "bonemerge" can be used for a model compiled with bone names that
        -- match the animation viewmodel.
        Mode = "bone",
        Bone = "jnt_backpack",

        -- Fine adjustment for custom backpack models. These values are applied
        -- in the local coordinate system of the animated backpack bone.
        -- Automatically anchors the visual center of armor/prop models to
        -- the animated backpack bone. This is recommended for TC13U armor.
        AutoCenter = true,
        CenterOffset = Vector(0, 0, 0),

        -- ForceVisible prevents the invisible animation driver from occluding
        -- the custom model in Garry's Mod's viewmodel depth pass.
        ForceVisible = true,

        -- Fine adjustment after automatic centering.
        Position = Vector(1, -10, -35),
        Angles = Angle(-70, 5, 10),
        Scale = 1.8,
        Skin = 0
    }
}

